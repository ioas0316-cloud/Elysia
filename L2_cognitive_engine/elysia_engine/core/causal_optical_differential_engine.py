"""
L2_cognitive_engine/elysia_engine/core/causal_optical_differential_engine.py

4-Axis Causal Optical Differential & Mismatch Localization Engine
================================================================
Implements rigorous physical discrimination between genuine real-world optical footage
and artificial generative distortions / deepfakes / hallucinations.

4 Causal Differential Axes:
1. Optical Wavefront Phase Continuity (Axis 1):
   - Physical optical camera lenses produce smooth, differentiable 2D wavefront phase surfaces.
   - Non-physical dislocations, joint breaking, and spatial warping produce phase tearing and gradient spikes.
2. Chromatic Triad Spectral Flux & Dispersion (Axis 2):
   - Natural light exhibits continuous spectral wavelength gradients (Red Flux, Blue Order, Yellow Entropy).
   - Generative artifacts cause unnatural chromatic inversion and color space tears.
3. Optical Edge Cliff & MTF Gradient Preservation (Axis 3):
   - Real glass optics preserve edge MTF sharpness and high-frequency boundaries according to pupil diffraction.
   - Bilinear blurring or hallucinated smoothing leads to MTF decay.
4. Thermodynamic Causal Friction Q_heat (Axis 4):
   - Computes causal friction heat generated by non-physical state transitions:
     Q_heat = ||grad Delta_Phi|| * (||Delta_Phi|| + Tension_Stiction)
   - Natural optical transitions maintain baseline thermal inertia; anomalies spike friction.
"""

from dataclasses import dataclass, field
from typing import Dict, Any, Tuple, Optional
import numpy as np


@dataclass
class CausalOpticalAssessmentReport:
    """Quantitative diagnostics and localization report for optical video transitions."""
    is_causally_natural: bool
    wavefront_phase_continuity_score: float
    chromatic_triad_coherence_score: float
    optical_edge_cliff_preservation: float
    mean_causal_friction_q_heat: float
    max_causal_friction_q_heat: float
    rupture_count: int
    rupture_ratio: float
    localization_heatmap: np.ndarray
    axis_scores: Dict[str, float] = field(default_factory=dict)


class CausalOpticalDifferentialEngine:
    """
    Engine evaluating optical field transitions against physical lens causality laws.
    Identifies localized generative hallucinations, anatomical joint breaking,
    and non-physical artifacts.
    """

    def __init__(
        self,
        heat_spike_threshold: float = 0.05,
        tension_multiplier: float = 10.0,
        rupture_threshold_ratio: float = 0.002
    ):
        self.heat_spike_threshold = heat_spike_threshold
        self.tension_multiplier = tension_multiplier
        self.rupture_threshold_ratio = rupture_threshold_ratio

    def extract_chromatic_triad(self, frame_rgb: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """
        Decomposes RGB into the Chromatic Triad:
        - Red (Flux): Dynamic thermodynamic carrier (approx. 620-750 nm)
        - Blue (Order): High-frequency structural wave (approx. 450-495 nm)
        - Yellow (Entropy): Dispersive dissipative phase (R + G blend approx. 570-590 nm)
        """
        r = frame_rgb[..., 0].astype(np.float32)
        g = frame_rgb[..., 1].astype(np.float32)
        b = frame_rgb[..., 2].astype(np.float32)

        flux_red = r - 0.5 * (g + b)
        order_blue = b - 0.5 * (r + g)
        entropy_yellow = 0.5 * (r + g) - b

        return flux_red, order_blue, entropy_yellow

    def estimate_global_phase_shift(self, im0: np.ndarray, im1: np.ndarray) -> Tuple[int, int]:
        """Estimates global camera pan/tilt translation vector via 2D phase correlation."""
        h, w = im0.shape
        f0 = np.fft.fft2(im0)
        f1 = np.fft.fft2(im1)
        eps = 1e-15
        cross_power = (f0 * np.conj(f1)) / (np.abs(f0 * np.conj(f1)) + eps)
        r = np.fft.ifft2(cross_power).real
        idx = np.unravel_index(np.argmax(r), (h, w))
        dy = idx[0] if idx[0] < h // 2 else idx[0] - h
        dx = idx[1] if idx[1] < w // 2 else idx[1] - w
        return int(dy), int(dx)

    def evaluate_causal_differential(
        self,
        frame_base: np.ndarray,
        frame_target: np.ndarray,
        is_subsampled: bool = True
    ) -> CausalOpticalAssessmentReport:
        """
        Compares frame_base and frame_target across the 4 causal axes.
        For consecutive video frames (e.g. camera pan), a natural physical transition yields
        is_causally_natural=True and low friction ruptures.
        """
        # Convert to float [0, 1]
        f0 = frame_base.astype(np.float32) / (255.0 if frame_base.dtype == np.uint8 else 1.0)
        f1 = frame_target.astype(np.float32) / (255.0 if frame_target.dtype == np.uint8 else 1.0)

        h, w = f0.shape[:2]

        # 1. Luminance & Spectral Delta
        lum0 = 0.299 * f0[..., 0] + 0.587 * f0[..., 1] + 0.114 * f0[..., 2]
        lum1 = 0.299 * f1[..., 0] + 0.587 * f1[..., 1] + 0.114 * f1[..., 2]

        # Estimate camera motion vector
        dy, dx = self.estimate_global_phase_shift(lum0, lum1)

        # Motion compensated target for differential field analysis
        if abs(dy) < h // 4 and abs(dx) < w // 4:
            f1_aligned = np.roll(f1, shift=(dy, dx), axis=(0, 1))
            lum1_aligned = np.roll(lum1, shift=(dy, dx), axis=(0, 1))
            pad_y = max(1, abs(dy) + 2)
            pad_x = max(1, abs(dx) + 2)
        else:
            f1_aligned = f1
            lum1_aligned = lum1
            pad_y = 1
            pad_x = 1

        delta_lum = lum1_aligned - lum0
        d_gy, d_gx = np.gradient(delta_lum)
        grad_delta_mag = np.sqrt(d_gx**2 + d_gy**2)

        # Axis 1: Optical Wavefront Phase Continuity
        laplacian_delta = np.abs(np.gradient(d_gx)[1] + np.gradient(d_gy)[0])
        valid_laplacian = laplacian_delta[pad_y:-pad_y, pad_x:-pad_x]
        phase_continuity_score = float(max(0.0, 1.0 - np.mean(valid_laplacian) * 15.0))

        # Axis 2: Chromatic Triad Spectral Flux & Dispersion
        r0, b0, y0 = self.extract_chromatic_triad(f0)
        r1, b1, y1 = self.extract_chromatic_triad(f1_aligned)
        triad_discrepancy = (np.abs(r1 - r0) + np.abs(b1 - b0) + np.abs(y1 - y0))[pad_y:-pad_y, pad_x:-pad_x]
        chromatic_coherence_score = float(max(0.0, 1.0 - np.mean(triad_discrepancy) * 4.0))

        # Axis 3: Optical Edge Cliff & MTF Gradient Preservation
        g0_y, g0_x = np.gradient(lum0)
        g1_y, g1_x = np.gradient(lum1_aligned)
        cliff0 = np.sqrt(g0_x**2 + g0_y**2)[pad_y:-pad_y, pad_x:-pad_x]
        cliff1 = np.sqrt(g1_x**2 + g1_y**2)[pad_y:-pad_y, pad_x:-pad_x]
        cliff_ratio = np.mean(cliff1) / (np.mean(cliff0) + 1e-6)
        edge_preservation_score = float(np.clip(1.0 - abs(cliff_ratio - 1.0) * 1.5, 0.0, 1.0))

        # Axis 4: Thermodynamic Causal Friction Q_heat
        # Q_heat = ||grad Delta_Phi|| * (||Delta_Phi|| + Tension_Stiction)
        friction_field = grad_delta_mag * (np.abs(delta_lum) + (1.0 / self.tension_multiplier))

        # Valid region (excluding boundary wrap margins)
        valid_friction = friction_field[pad_y:-pad_y, pad_x:-pad_x]
        mean_q_heat = float(np.mean(valid_friction))
        max_q_heat = float(np.max(valid_friction))

        # Localization Heatmap: Pinpoints regions exceeding stiction barrier
        rupture_mask = valid_friction > self.heat_spike_threshold
        rupture_count = int(np.sum(rupture_mask))
        rupture_ratio = float(rupture_count / max(1, valid_friction.size))

        # Normalize full localization heatmap to [0, 1] for visualization
        norm_heatmap = friction_field / (np.percentile(valid_friction, 99.0) + 1e-6)
        norm_heatmap = np.clip(norm_heatmap, 0.0, 1.0)
        norm_heatmap[:pad_y, :] = 0.0
        norm_heatmap[-pad_y:, :] = 0.0
        norm_heatmap[:, :pad_x] = 0.0
        norm_heatmap[:, -pad_x:] = 0.0

        # Causal classification: natural physical motion vs rupture anomaly
        is_natural = (rupture_ratio < self.rupture_threshold_ratio) and (mean_q_heat < self.heat_spike_threshold * 0.25)

        axis_scores = {
            "Axis 1 - Wavefront Continuity": phase_continuity_score,
            "Axis 2 - Chromatic Coherence": chromatic_coherence_score,
            "Axis 3 - Edge MTF Preservation": edge_preservation_score,
            "Axis 4 - Causal Invariance (1 - Q_heat)": float(max(0.0, 1.0 - mean_q_heat * 20.0))
        }

        return CausalOpticalAssessmentReport(
            is_causally_natural=is_natural,
            wavefront_phase_continuity_score=phase_continuity_score,
            chromatic_triad_coherence_score=chromatic_coherence_score,
            optical_edge_cliff_preservation=edge_preservation_score,
            mean_causal_friction_q_heat=mean_q_heat,
            max_causal_friction_q_heat=max_q_heat,
            rupture_count=rupture_count,
            rupture_ratio=rupture_ratio,
            localization_heatmap=norm_heatmap,
            axis_scores=axis_scores
        )
