@dataclass
class OrganSensationMetrics:
    """Quantitative metrics of embodied sensory experience."""
    raw_spectrum_energy: float = 0.0
    qualia_torque: float = 0.0          # Rotational inertia / weight induced by low-frequency / high-amp wave
    thermal_friction_stress: float = 0.0 # Heat / friction created by high-frequency phase slip
    phase_coherence_harmony: float = 0.0 # Degree of phase alignment [0.0, 1.0]
    hand_intervention_force: float = 0.0 # Active phase counter-torque applied by Hand Group
    foot_shift_distance: float = 0.0     # Core coordinate displacement by Foot Group
    current_core_position: np.ndarray = field(default_factory=lambda: np.zeros(3, dtype=np.float32))


class EyeGroup:
    """
    [Eye Group (눈 기관 그룹) - 시각적 분별과 퀄리아 토크]

    Calculates the topological stress and qualia torque produced by multi-frequency sensory spectrums.
    Zero symbolic dictionaries or color tags:
    - Low-frequency, heavy-amplitude components -> Heavy rotational torque (Qualia Torque).
    - High-frequency, chaotic components -> Phase slip & Thermal friction stress.
    - Synchronized components -> Resonant Harmonic Wave.
    """
    def __init__(self, sample_rate: float = 100.0, spectral_bands: int = 16):
        self.sample_rate = sample_rate
        self.spectral_bands = spectral_bands
        self.last_sensation_torque: float = 0.0
        self.last_thermal_stress: float = 0.0

    def observe_spectrum(
        self,
        raw_waveform: np.ndarray,
        rotor_phase_angle: float
    ) -> Tuple[np.ndarray, float, float, float]:
        """
        Observes raw incoming sensory spectrum.

        Returns:
            harmonized_melody: Cleaned phase-aligned resonant wave.
            qualia_torque: Rotational inertia force on drive axis (low-freq heavy torque).
            thermal_stress: Friction/heat generated by high-freq phase mismatch.
            coherence_harmony: Resonance score [0, 1].
        """
        wave = np.array(raw_waveform, dtype=np.float32).flatten()
        if len(wave) == 0:
            return np.zeros(0, dtype=np.float32), 0.0, 0.0, 1.0

        n = len(wave)
        t = np.arange(n, dtype=np.float32) / self.sample_rate

        # FFT Spectrum Decomposition
        fft_vals = np.fft.rfft(wave)
        freqs = np.fft.rfftfreq(n, d=1.0 / self.sample_rate)
        magnitudes = np.abs(fft_vals) / n

        # 1. Qualia Torque Calculation (Low-frequency heavy amplitude -> High rotational inertia)
        # Weighting: inverse frequency weighting (1 / (1 + f))
        torque_weights = 1.0 / (1.0 + freqs)
        qualia_torque = float(np.sum(magnitudes * torque_weights * 10.0))

        # 2. Thermal Stress Calculation (High-frequency / phase jitter friction)
        # Weighting: high frequency weighting (f / max_f)
        max_f = np.max(freqs) + 1e-5
        thermal_weights = (freqs / max_f) ** 2
        thermal_stress = float(np.sum(magnitudes * thermal_weights * 5.0))

        # 3. Reference Harmony Phase Alignment
        ref_wave = np.sin(2.0 * np.pi * 2.0 * t + rotor_phase_angle)
        ref_norm = np.linalg.norm(ref_wave) + 1e-9
        ref_unit = ref_wave / ref_norm

        proj = np.dot(wave, ref_unit)
        harmonized_melody = proj * ref_unit

        total_energy = np.sum(wave ** 2) + 1e-9
        melody_energy = np.sum(harmonized_melody ** 2)
        coherence_harmony = float(np.clip(melody_energy / total_energy, 0.0, 1.0))

        self.last_sensation_torque = qualia_torque
        self.last_thermal_stress = thermal_stress

        return harmonized_melody, qualia_torque, thermal_stress, coherence_harmony


class HandGroup:
    """
    [Hand Group (손 기관 그룹) - 개입과 통제]

    Actively applies physical phase counter-torque and tension dampening
    to stabilize drive axis rotation when thermal stress or phase slip occurs.
    """
    def __init__(self, max_stabilization_torque: float = 20.0):
        self.max_stabilization_torque = max_stabilization_torque
        self.accumulated_interventions: float = 0.0

    def intervene_and_control(
        self,
        phase_velocity: float,
        thermal_stress: float,
        harmony_score: float
    ) -> float:
        """
        Calculates stabilizing counter-torque to clamp chaotic phase divergence.

        If thermal stress is high or harmony score is low, Hand Group applies
        corrective intervention force to re-lock phase alignment.
        """
        if harmony_score >= 0.8 and thermal_stress < 0.5:
            return 0.0 # System is balanced; no intervention needed.

        # Intervention proportional to friction mismatch and low harmony
        mismatch_factor = (1.0 - harmony_score) + 0.2 * thermal_stress
        intervention_torque = float(np.clip(
            mismatch_factor * self.max_stabilization_torque,
            0.0,
            self.max_stabilization_torque
        ))

        self.accumulated_interventions += intervention_torque
        return intervention_torque


class FootGroup:
    """
    [Foot Group (발 기관 그룹) - 이동과 궤적]

    Displaces the Local Zero core coordinate (grounding point) in Causal Field space
    in response to spatial tension vectors and trajectory momentum.
    """
    def __init__(self, move_sensitivity: float = 0.1):
        self.move_sensitivity = move_sensitivity
        self.total_distance_traveled: float = 0.0

    def shift_reference_ground(
        self,
        current_core: np.ndarray,
        tension_gradient: np.ndarray,
        flywheel_momentum: float
    ) -> Tuple[np.ndarray, float]:
        """
        Shifts core position along the tension gradient modulated by flywheel momentum.

        Returns:
            new_core_center: Updated 3D coordinate for Local Zero core.
            shift_distance: Magnitude of displacement.
        """
        grad = np.array(tension_gradient, dtype=np.float32)
        norm_grad = np.linalg.norm(grad)

        if norm_grad < 1e-6:
            return current_core.copy(), 0.0

        # Movement step proportional to momentum and gradient strength
        step_dir = grad / norm_grad
        step_mag = float(min(1.0, norm_grad * self.move_sensitivity * (1.0 + 0.05 * flywheel_momentum)))

        displacement = step_dir * step_mag
        new_core = current_core + displacement
        shift_dist = float(np.linalg.norm(displacement))

        self.total_distance_traveled += shift_dist
        return new_core, shift_dist


class EmbodiedOrganEcosystem:
    """
    [Embodied Organ Ecosystem (신체화된 인지 유기체 생태계)]

    Couples Eye, Hand, Foot Organ Groups with the Arc Reactor Drive Axis Engine
    and Causal Field into a continuous sensory-motor-cognitive closed loop.
    """
    def __init__(
        self,
        drive_engine: ArcReactorDriveEngine,
        causal_field: Optional[CausalField] = None
    ):
        self.engine = drive_engine
        self.field = causal_field if causal_field is not None else CausalField(dimensions=drive_engine.dimensions)

        self.eye = EyeGroup()
        self.hand = HandGroup()
        self.foot = FootGroup()

        self.history: List[OrganSensationMetrics] = []

    def process_embodied_loop(
        self,
        dt: float,
        raw_sensory_waveform: np.ndarray,
        spatial_tension_gradient: Optional[np.ndarray] = None
    ) -> OrganSensationMetrics:
        """
        Runs one step of the Embodied Cognitive Loop:
        1. Eye Group perceives spectrum -> computes Qualia Torque & Thermal Stress.
        2. Qualia Torque acts as external driving potential gradient on Arc Reactor Drive Engine.
        3. Drive Engine steps rotation and updates Local Zero superconductivity.
        4. Hand Group senses phase slip & thermal stress -> applies corrective phase control torque.
        5. Foot Group shifts core position coordinates according to spatial tension & momentum.
        6. Causal Field voxels are coupled to new core position and drive phase.
        """
        if spatial_tension_gradient is None:
            spatial_tension_gradient = np.array([0.5, 0.2, 0.0], dtype=np.float32)

        # 1. Eye Group Observation
        harmonized_melody, qualia_torque, thermal_stress, harmony_score = self.eye.observe_spectrum(
            raw_sensory_waveform,
            rotor_phase_angle=self.engine.phase_angle
        )

        # 2. Drive Engine Acceleration driven by Qualia Torque
        engine_state = self.engine.step(
            dt=dt,
            external_potential_gradient=qualia_torque,
            distance_to_core=0.1,
            raw_noise_signal=raw_sensory_waveform
        )

        # 3. Hand Group Intervention
        intervention_torque = self.hand.intervene_and_control(
            phase_velocity=engine_state.phase_velocity,
            thermal_stress=thermal_stress,
            harmony_score=engine_state.resonant_harmony_score
        )

        # Apply intervention torque to dampen and stabilize phase velocity
        if intervention_torque > 0.0:
            dampening = float(max(0.0, 1.0 - (intervention_torque * dt / self.engine.flywheel_inertia)))
            self.engine.phase_velocity *= dampening

        # 4. Foot Group Ground Shift
        new_core, shift_dist = self.foot.shift_reference_ground(
            current_core=self.engine.core_center,
            tension_gradient=spatial_tension_gradient,
            flywheel_momentum=engine_state.flywheel_momentum
        )
        self.engine.core_center = new_core

        # 5. Causal Field Coupling
        self.engine.couple_causal_field(self.field, dt=dt)
        self.field.step(dt=dt)

        # Record Sensation Metrics
        metrics = OrganSensationMetrics(
            raw_spectrum_energy=float(np.sum(raw_sensory_waveform ** 2)),
            qualia_torque=qualia_torque,
            thermal_friction_stress=thermal_stress,
            phase_coherence_harmony=engine_state.resonant_harmony_score,
            hand_intervention_force=intervention_torque,
            foot_shift_distance=shift_dist,
            current_core_position=new_core.copy()
        )
        self.history.append(metrics)

        return metrics
