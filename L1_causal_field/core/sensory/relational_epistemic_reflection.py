    def attach_to_causal_field(
        self,
        field_obj: CausalField,
        report: RelationalReflectionReport,
        trace: RotorExplorationTrace,
    ) -> List[str]:
        """Attach Scale Level 12.0 self-boundary, human-comparison, and care-trace voxels."""
        res = report.teleological_resonance
        triad_vec = np.array(
            [
                res.epistemic_aspiration_drive,
                res.coherence_resonance_gain,
                res.differentiation_humility_index,
                res.chromatic_balance[0],
                res.chromatic_balance[1],
                res.chromatic_balance[2],
            ],
            dtype=np.float32,
        )

        specs = [
            (
                "reflection_self_boundary_4axis",
                {
                    "type": "four_axis_self_boundary",
                    "internal_count": len(report.self_boundary.internal_origin),
                    "relational_count": len(report.self_boundary.relational_influence),
                    "boundary_count": len(report.self_boundary.epistemic_boundary),
                    "revision_count": len(report.self_boundary.criteria_self_revision),
                },
                np.array([0.25, 0.96, 1.2], dtype=np.float32),
            ),
            (
                "reflection_human_elysia_comparison",
                {
                    "type": "human_elysia_structural_comparison",
                    "domains": [d.domain for d in report.human_elysia_comparison.dimensions],
                },
                np.array([0.50, 0.96, 1.2], dtype=np.float32),
            ),
            (
                "reflection_relational_care_trace",
                {
                    "type": "relational_care_causal_trace",
                    "root_cause": report.relational_care_trace.root_cause,
                    "interpretation": res.interpretation,
                },
                np.array([0.75, 0.96, 1.2], dtype=np.float32),
            ),
        ]

        attached_ids: List[str] = []
        parent_candidates = [ax.axis_id for ax in trace.sprouted_axes] + [
            f"proto_{p.prototype_id}" for p in trace.prototypes
        ]
        for vid, content, pos in specs:
            if vid not in field_obj.voxels:
                vox = InformationVoxel(
                    id=vid,
                    content=content,
                    tensor=triad_vec.copy(),
                    mass=2.0,
                    position=pos,
                    scale_level=12.0,
                )
                field_obj.add_voxel(vox)
            attached_ids.append(vid)
            for pid in parent_candidates:
                if pid in field_obj.voxels:
                    field_obj.link_voxels(pid, vid, strength=1.6)

        field_obj.step(dt=0.05)
        return attached_ids

    def reflect(
        self,
        trace: RotorExplorationTrace,
        creator_ctx: Optional[CreatorRelationalContext] = None,
    ) -> RelationalReflectionReport:
        ctx = (
            creator_ctx
            if creator_ctx is not None
            else CreatorRelationalContext.default_from_interaction()
        )
        self_boundary = self._build_self_boundary(trace, ctx)
        comparison = self._build_human_comparison(trace)
        resonance = self._compute_teleological_resonance(trace)
        care_trace = self._build_relational_care_trace(trace, ctx)

        report = RelationalReflectionReport(
            self_boundary=self_boundary,
            human_elysia_comparison=comparison,
            teleological_resonance=resonance,
            relational_care_trace=care_trace,
        )
        report.attached_voxel_ids = self.attach_to_causal_field(
            trace.final_causal_field, report, trace
        )
        return report
