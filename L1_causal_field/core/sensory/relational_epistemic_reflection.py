    def _compute_teleological_resonance(
        self, trace: RotorExplorationTrace
    ) -> TeleologicalResonanceState:
        n_rec = max(1, len(trace.region_records))
        aniso_recs = [r for r in trace.region_records if r.mechanical_rotor.is_anisotropic]
        n_aniso = len(aniso_recs)
        n_cleave_ok = sum(1 for r in aniso_recs if r.cleavage_confirmed)
        n_axes = len(trace.sprouted_axes)
        n_rev = len(trace.criteria_revisions)
        n_xfer = len(trace.rotor_transfer_confirmations)
        n_limits = len(trace.organ_audit.modality_limits)
        max_surp = max([r.prediction_surprise for r in trace.region_records] + [0.0])

        # Red (Flux / Aspiration): unresolved epistemic horizon + surprise converted into new axes
        horizon_ratio = float(n_limits) / float(n_limits + 4)
        axis_growth_ratio = min(1.0, float(n_axes) / float(max(1, n_rec - 1)))
        surp_flux = min(1.0, max_surp / 3.0)
        red_aspiration = float(
            np.clip(0.35 * horizon_ratio + 0.40 * axis_growth_ratio + 0.25 * surp_flux, 0.0, 1.0)
        )

        # Blue (Order / Coherence Resonance): verified cleavage, frame-invariant transfer, shared invariants
        cleave_acc = float(n_cleave_ok / n_aniso) if n_aniso > 0 else 1.0
        transfer_acc = float(n_xfer / max(1, n_aniso - 1)) if n_aniso >= 2 else 0.0
        shared_proto_acc = float(
            sum(1 for p in trace.prototypes if p.confirmation_count >= 2) / max(1, len(trace.prototypes))
        )
        blue_coherence = float(
            np.clip(0.50 * cleave_acc + 0.30 * min(1.0, transfer_acc) + 0.20 * shared_proto_acc, 0.0, 1.0)
        )

        # Yellow (Differentiation / Epistemic Humility): clean splits without averaging + explicit bounds
        surp_events = sum(1 for r in trace.region_records if r.prediction_surprise > 0.75)
        split_clarity = min(1.0, float(n_rev + n_axes) / float(max(1, surp_events + 1)))
        humility_bound = min(1.0, float(n_limits + 2) / 6.0)
        yellow_humility = float(np.clip(0.60 * split_clarity + 0.40 * humility_bound, 0.0, 1.0))

        tot = red_aspiration + blue_coherence + yellow_humility
        if tot > 1e-9:
            balance = (
                float(red_aspiration / tot),
                float(blue_coherence / tot),
                float(yellow_humility / tot),
            )
        else:
            balance = (1.0 / 3.0, 1.0 / 3.0, 1.0 / 3.0)

        interp = (
            f"Derived strictly from telemetry: {n_cleave_ok}/{n_aniso} anisotropic cleavages confirmed, "
            f"{n_xfer} zero-shot rotor transfers, {n_axes} deterministic axes sprouted across {n_rec} regions, "
            f"max_surprise={max_surp:.2f}, {n_limits} explicit optical/sensory horizon bounds retained."
        )
        return TeleologicalResonanceState(
            epistemic_aspiration_drive=red_aspiration,
            coherence_resonance_gain=blue_coherence,
            differentiation_humility_index=yellow_humility,
            chromatic_balance=balance,
            interpretation=interp,
        )

