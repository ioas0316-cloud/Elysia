"""
Project Elysia: Perceptual Probe Skill & Relational Void Engine
================================================================
Transforms flat, static commands into active Perceptual Probes (Cognitive Sensing Organs).
Instead of isolated 1:1 scalar functions (Input -> Output), skills are modeled as active
tentacles probing the 4D/5D Causal Spacetime Topology.

Key Concepts:
1. Perceptual Probe Skill (능동적 감각 촉수 스킬):
   Probes external state & CausalField, measuring physical/informational friction error E.
2. Relational Void Probe (관계적 공백 인지 촉수):
   Detects negative-space constraints where unobserved causes must exist to hold the
   surrounding causal network together.
3. Skill Adaptability Map & Tacit Knowledge (위상적 노하우 축적):
   Fine-tunes skill phase rotors (Clifford Rotors / Phase Vectors) along error gradients,
   accumulating experiential intelligence (Tacit Knowledge) across contexts.
4. Causal Field Feedback Loop (인과장 반사 루프):
   Feeds back friction and phase deformation into CausalField voxels, altering local potential.
"""

from dataclasses import dataclass, field
import numpy as np
from typing import Dict, List, Any, Optional, Tuple, Callable
from core.physics.causal_field import CausalField, InformationVoxel


@dataclass
class ProbeFeedback:
    """Feedback payload returned when a PerceptualProbeSkill probes the environment."""
    skill_id: str
    target_context: str
    phase_divergence: float
    friction_error: float # Friction/Error (\mathcal{E})
    relational_void_tension: float # Negative space constraint tension
    calibrated_output: np.ndarray
    rotor_phase_shift: float
    tacit_knowledge_gain: float
    field_impact: Dict[str, Any]


class RelationalVoidProbe:
    """
    [Relational Locus / Topological Void Probe (관계적 공백 인지 촉수)]
    Infers negative space in the causal field where an unobserved principle or force
    MUST exist to satisfy topological conservation laws among surrounding voxels.
    """
    def __init__(self, dimension: int = 5):
        self.dimension = dimension

    def detect_relational_void(
        self,
        causal_field: CausalField,
        active_probe_vector: np.ndarray
    ) -> Tuple[float, np.ndarray]:
        """
        Calculates the negative space tension generated by surrounding voxels
        and projects the implied void center vector.
        """
        if not causal_field.voxels:
            return 0.0, np.zeros(self.dimension, dtype=np.float32)

        probe_vec = np.array(active_probe_vector, dtype=np.float32).flatten()
        if len(probe_vec) < self.dimension:
            probe_vec = np.pad(probe_vec, (0, self.dimension - len(probe_vec)))
        elif len(probe_vec) > self.dimension:
            probe_vec = probe_vec[:self.dimension]

        # Aggregate surrounding voxel potentials and tensor positions
        void_vector = np.zeros(self.dimension, dtype=np.float32)
        total_potential_deficit = 0.0

        voxel_list = list(causal_field.voxels.values())
        for v in voxel_list:
            v_tensor = v.tensor.flatten()
            if len(v_tensor) < self.dimension:
                v_tensor = np.pad(v_tensor, (0, self.dimension - len(v_tensor)))
            elif len(v_tensor) > self.dimension:
                v_tensor = v_tensor[:self.dimension]

            # Measure asymmetry/deficit between probe and voxel
            diff = probe_vec - v_tensor
            dist = np.linalg.norm(diff) + 1e-6
            # Higher potential or entropy indicates missing relational bridge
            deficit = (1.0 - v.potential) / dist
            void_vector += diff * deficit
            total_potential_deficit += abs(deficit)

        avg_deficit = float(total_potential_deficit / max(1, len(voxel_list)))
        void_norm = np.linalg.norm(void_vector)
        if void_norm > 1e-6:
            implied_void_direction = void_vector / void_norm
        else:
            implied_void_direction = np.zeros(self.dimension, dtype=np.float32)

        # Relational Void tension is high when surrounding constraints intersect with high deficit
        relational_void_tension = float(np.tanh(avg_deficit * void_norm))
        return relational_void_tension, implied_void_direction


class SkillAdaptabilityMap:
    """
    [Skill Adaptability Map & Tacit Knowledge Storage (노하우 위상 지표)]
    Stores topological phase deformations and accumulated tacit knowledge per context.
    A skill fine-tunes its Clifford Rotor or Phase Vector over time rather than resetting.
    """
    def __init__(self, dimension: int = 5):
        self.dimension = dimension
        # Map: context_name -> phase_rotor_vector (ndarray)
        self.context_rotors: Dict[str, np.ndarray] = {}
        # Map: context_name -> accumulated tacit knowledge score (float)
        self.tacit_knowledge_acc: Dict[str, float] = {}

    def get_context_rotor(self, context_name: str) -> np.ndarray:
        if context_name not in self.context_rotors:
            # Default identity rotor on 5D unit sphere
            rotor = np.zeros(self.dimension, dtype=np.float32)
            rotor[0] = 1.0
            self.context_rotors[context_name] = rotor
            self.tacit_knowledge_acc[context_name] = 0.0
        return self.context_rotors[context_name]

    def update_context_rotor(
        self,
        context_name: str,
        gradient_shift: np.ndarray,
        friction_error: float,
        learning_rate: float = 0.15
    ) -> Tuple[np.ndarray, float]:
        rotor = self.get_context_rotor(context_name)
        shift = np.array(gradient_shift, dtype=np.float32).flatten()
        if len(shift) < self.dimension:
            shift = np.pad(shift, (0, self.dimension - len(shift)))
        elif len(shift) > self.dimension:
            shift = shift[:self.dimension]

        # Rotor fine-tuning along error gradient
        new_rotor = rotor - learning_rate * shift
        norm = np.linalg.norm(new_rotor)
        if norm > 1e-6:
            new_rotor /= norm
        else:
            new_rotor = rotor

        # Tacit knowledge accumulates when error reduces and phase stabilizes
        knowledge_gain = float(1.0 / (1.0 + friction_error) * 0.1)
        self.context_rotors[context_name] = new_rotor
        self.tacit_knowledge_acc[context_name] += knowledge_gain

        return new_rotor, knowledge_gain

    def get_tacit_knowledge(self, context_name: str) -> float:
        return self.tacit_knowledge_acc.get(context_name, 0.0)


class PerceptualProbeSkill:
    """
    [Perceptual Probe Skill (능동적 감각 촉수 스킬)]
    Re-defines commands as active probing tentacles.
    Performs probing, measures friction error E, senses Relational Voids,
    fine-tunes phase rotors, and feeds back into the Causal Field.
    """
    def __init__(
        self,
        skill_id: str,
        name: str,
        base_probe_func: Callable[[np.ndarray], np.ndarray],
        dimension: int = 5,
        learning_rate: float = 0.2
    ):
        self.skill_id = skill_id
        self.name = name
        self.base_probe_func = base_probe_func
        self.dimension = dimension
        self.learning_rate = learning_rate

        self.void_probe = RelationalVoidProbe(dimension=dimension)
        self.adaptability_map = SkillAdaptabilityMap(dimension=dimension)
        self.execution_count: int = 0
        self.last_friction_error: float = 1.0

    def probe_and_execute(
        self,
        input_state: np.ndarray,
        causal_field: Optional[CausalField] = None,
        context_name: str = "default_context",
        target_voxel_id: Optional[str] = None
    ) -> ProbeFeedback:
        """
        Executes the skill as an active sensory probe:
        1. Retrieves context phase rotor from SkillAdaptabilityMap.
        2. Computes base raw probe response modified by context rotor.
        3. Probes CausalField for friction error E & phase divergence.
        4. Detects Relational Void tension & missing causal direction.
        5. Fine-tunes skill rotor via gradient descent on error E.
        6. Feeds back friction & rotor shift into CausalField.
        """
        self.execution_count += 1
        state_vec = np.array(input_state, dtype=np.float32).flatten()
        if len(state_vec) < self.dimension:
            state_vec = np.pad(state_vec, (0, self.dimension - len(state_vec)))
        elif len(state_vec) > self.dimension:
            state_vec = state_vec[:self.dimension]

        # 1. Retrieve current phase rotor (Tacit Knowledge state)
        rotor = self.adaptability_map.get_context_rotor(context_name)

        # 2. Raw skill output modulated by current rotor phase alignment
        raw_output = self.base_probe_func(state_vec)
        raw_output = np.array(raw_output, dtype=np.float32).flatten()
        if len(raw_output) < self.dimension:
            raw_output = np.pad(raw_output, (0, self.dimension - len(raw_output)))
        elif len(raw_output) > self.dimension:
            raw_output = raw_output[:self.dimension]

        calibrated_probe = raw_output * rotor

        # 3. Field Probing & Friction Calculation
        friction_error = 0.0
        phase_divergence = 0.0
        field_impact_report = {}

        if causal_field is not None:
            field_res = causal_field.observe_external_stimulus(
                raw_stimulus=calibrated_probe,
                target_voxel_id=target_voxel_id
            )
            if field_res["observations"]:
                obs0 = field_res["observations"][0]
                friction_error = obs0["friction_score"]
                phase_divergence = obs0["phase_divergence"]
            field_impact_report = field_res
        else:
            # Fallback direct friction without causal field
            diff = calibrated_probe - state_vec
            friction_error = float(np.linalg.norm(diff))
            phase_divergence = float(np.arccos(np.clip(
                np.dot(calibrated_probe, state_vec) / (np.linalg.norm(calibrated_probe)*np.linalg.norm(state_vec) + 1e-6),
                -1.0, 1.0
            )))

        # 4. Relational Void Sensing
        void_tension = 0.0
        void_dir = np.zeros(self.dimension, dtype=np.float32)
        if causal_field is not None:
            void_tension, void_dir = self.void_probe.detect_relational_void(causal_field, calibrated_probe)

        # 5. Rotor Fine-Tuning & Tacit Knowledge Accumulation
        # Error gradient combining friction error and relational void vector
        gradient = (calibrated_probe - state_vec) * (1.0 + friction_error) + void_dir * void_tension
        updated_rotor, knowledge_gain = self.adaptability_map.update_context_rotor(
            context_name=context_name,
            gradient_shift=gradient,
            friction_error=friction_error,
            learning_rate=self.learning_rate
        )

        rotor_shift = float(np.linalg.norm(updated_rotor - rotor))
        self.last_friction_error = friction_error

        # Final output after topological adaptation
        final_calibrated_output = raw_output * updated_rotor

        # 6. Feedback loop into CausalField voxels
        if causal_field is not None and target_voxel_id in causal_field.voxels:
            target_v = causal_field.voxels[target_voxel_id]
            # Inject impact impulse proportional to rotor shift and void tension
            impact_impulse = (updated_rotor - rotor) * (1.0 + void_tension)
            causal_field.apply_impact(target_voxel_id, impact_impulse[:len(target_v.velocity)])

        return ProbeFeedback(
            skill_id=self.skill_id,
            target_context=context_name,
            phase_divergence=phase_divergence,
            friction_error=friction_error,
            relational_void_tension=void_tension,
            calibrated_output=final_calibrated_output,
            rotor_phase_shift=rotor_shift,
            tacit_knowledge_gain=knowledge_gain,
            field_impact=field_impact_report
        )


class PerceptualProbeEngine:
    """
    [Perceptual Probe Engine (인지적 감각 촉수 관리 엔진)]
    Coordinates a collection of PerceptualProbeSkills within an agent or system ecosystem.
    Allows dynamic registration, execution, and comparison between flat execution vs probe execution.
    """
    def __init__(self, dimension: int = 5):
        self.dimension = dimension
        self.skills: Dict[str, PerceptualProbeSkill] = {}

    def register_skill(self, skill: PerceptualProbeSkill):
        self.skills[skill.skill_id] = skill

    def execute_skill_probe(
        self,
        skill_id: str,
        input_state: np.ndarray,
        causal_field: Optional[CausalField] = None,
        context_name: str = "default_context",
        target_voxel_id: Optional[str] = None
    ) -> ProbeFeedback:
        if skill_id not in self.skills:
            raise KeyError(f"Skill '{skill_id}' not registered in PerceptualProbeEngine.")

        skill = self.skills[skill_id]
        return skill.probe_and_execute(
            input_state=input_state,
            causal_field=causal_field,
            context_name=context_name,
            target_voxel_id=target_voxel_id
        )

    def get_tacit_knowledge_summary(self, context_name: str) -> Dict[str, float]:
        return {
            skill_id: skill.adaptability_map.get_tacit_knowledge(context_name)
            for skill_id, skill in self.skills.items()
        }
